"""Builds ExtraUz.java / ExtraRu.java from the i18n/*.tsv translation files.

Run from the Anormal project root:  python i18n_gen.py
Each TSV line is:  English key <TAB> translation
"""

import pathlib

ROOT = pathlib.Path('src/main/java/com/anormal/client/i18n')
DATA = pathlib.Path('i18n')
BS = chr(92)


def load_tsv(path):
    rows = []
    if not path.exists():
        return rows
    seen = set()
    for line in path.read_text(encoding='utf-8').splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if '\t' not in line:
            continue
        key, value = line.split('\t', 1)
        key, value = key.strip(), value.strip()
        if not key or not value or key in seen:
            continue
        seen.add(key)
        rows.append((key, value))
    return rows


def esc(text):
    out = []
    for ch in text:
        if ch == BS or ch == '"':
            out.append(BS + ch)
        elif ord(ch) < 32:
            out.append(' ')
        else:
            out.append(ch)
    return ''.join(out)


TEMPLATE = '''package com.anormal.client.i18n;

import java.util.Map;

/** Additional {lang} translations, generated by i18n_gen.py from i18n/{file}.tsv. */
final class {cls} {{
    private {cls}() {{}}

    static void load(Map<String, String> m) {{
        for (String[] e : entries()) m.put(e[0], e[1]);
    }}

    private static String[][] entries() {{
        return new String[][] {{
{body}
        }};
    }}
}}
'''


def write(cls, lang, pattern, target):
    rows = []
    seen = set()
    for path in sorted(DATA.glob(pattern)):
        for k, v in load_tsv(path):
            if k in seen:
                continue
            seen.add(k)
            rows.append((k, v))
    body = ',\n'.join('                {"%s", "%s"}' % (esc(k), esc(v)) for k, v in rows)
    if body:
        body += ','
    (ROOT / target).write_text(
        TEMPLATE.format(lang=lang, file=pattern[:-4], cls=cls, body=body), encoding='utf-8')
    print(target, '->', len(rows), 'entries')


write('ExtraUz', 'Uzbek', 'uz*.tsv', 'ExtraUz.java')
write('ExtraRu', 'Russian', 'ru*.tsv', 'ExtraRu.java')
